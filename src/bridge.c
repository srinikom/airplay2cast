/* ---------------------------------------------------------------- helpers */

int local_ip_for(const char *remote_ip, char *out, size_t cap) {
  int fd = socket(AF_INET, SOCK_DGRAM | SOCK_CLOEXEC, 0);
  if (fd < 0)
    return -1;
  struct sockaddr_in a = {.sin_family = AF_INET, .sin_port = htons(9)};
  if (inet_pton(AF_INET, remote_ip, &a.sin_addr) != 1 ||
      connect(fd, (struct sockaddr *)&a, sizeof(a)) < 0) {
    close(fd);
    return -1;
  }
  struct sockaddr_in l;
  socklen_t ll = sizeof(l);
  int r = getsockname(fd, (struct sockaddr *)&l, &ll);
  close(fd);
  if (r < 0 || !inet_ntop(AF_INET, &l.sin_addr, out, (socklen_t)cap))
    return -1;
  return 0;
}

uint64_t airplay_device_id_for(const char *cast_id) {
  uint64_t h = 0xcbf29ce484222325ULL; /* FNV-1a */
  for (const char *p = cast_id; *p; p++) {
    h ^= (uint8_t)*p;
    h *= 0x100000001b3ULL;
  }
  h &= 0xFFFFFFFFFFFFULL;
  /* first octet: unicast, locally administered */
  uint64_t first = ((h >> 40) & 0xFC) | 0x02;
  return (h & 0xFFFFFFFFFFULL) | (first << 40);
}

static void cfg_escape(char *out, size_t cap, const char *in) {
  size_t n = 0;
  for (; *in && n + 2 < cap; in++) {
    if (*in == '"' || *in == '\\')
      out[n++] = '\\';
    out[n++] = *in;
  }
  out[n] = 0;
}

static double airplay_db_to_level(double db) {
  if (db <= -100)
    return 0;
  double l = (db + 30.0) / 30.0;
  return l < 0 ? 0 : l > 1 ? 1 : l;
}

/* ---------------------------------------------------------------- shairport-sync */

static int write_sps_config(device *d, char *path, size_t cap) {
  const bridge_config *cfg = d->cfg;
  char name[400];
  cfg_escape(name, sizeof(name), d->airplay_name);
  snprintf(path, cap, "%s/%s.conf", cfg->state_dir, d->info.id);
  FILE *f = fopen(path, "w");
  if (!f) {
    LOGE("%s: cannot write %s: %s", d->tag, path, strerror(errno));
    return -1;
  }
  fprintf(f,
          "// generated by airplay2cast for Cast device %s (%s)\n"
          "general = {\n"
          "  name = \"%s\";\n"
          "  output_backend = \"stdout\";\n"
          "  mdns_backend = \"avahi\";\n"
          "  port = %d;\n"
          "  airplay_device_id = 0x%012llXL;\n"
          "  nqptp_shared_memory_interface_name = \"/ap2c-%.24s\";\n"
          "  ignore_volume_control = \"%s\";\n"
          "};\n"
          "stdout = {\n"
          "  output_rate = %d;\n"
          "  output_format = \"S16_LE\";\n"
          "  output_channels = 2;\n"
          "};\n"
          "metadata = {\n"
          "  enabled = \"yes\";\n"
          "  include_cover_art = \"no\";\n"
          "  socket_address = \"127.0.0.1\";\n"
          "  socket_port = %d;\n"
          "  socket_msglength = 65000;\n"
          "};\n"
          "diagnostics = {\n"
          "  log_verbosity = %d;\n"
          "};\n",
          d->info.id, d->info.ip, name, cfg->base_port + d->slot,
          (unsigned long long)airplay_device_id_for(d->info.id), d->info.id,
          cfg->hw_volume ? "yes" : "no", cfg->rate, d->meta_port, cfg->sps_verbosity);
  fclose(f);
  return 0;
}

static pid_t spawn_sps(device *d, const char *conf, int *out_fd, int *err_fd) {
  int po[2], pe[2];
  if (pipe2(po, O_CLOEXEC) < 0)
    return -1;
  if (pipe2(pe, O_CLOEXEC) < 0) {
    close(po[0]), close(po[1]);
    return -1;
  }
  pid_t pid = fork();
  if (pid == 0) {
    prctl(PR_SET_PDEATHSIG, SIGTERM);
    signal(SIGPIPE, SIG_DFL);
    signal(SIGINT, SIG_DFL);
    signal(SIGTERM, SIG_DFL);
    sigset_t none;
    sigemptyset(&none);
    sigprocmask(SIG_SETMASK, &none, NULL);
    dup2(po[1], STDOUT_FILENO);
    dup2(pe[1], STDERR_FILENO);
    execl(d->cfg->sps_bin, d->cfg->sps_bin, "-c", conf, (char *)NULL);
    dprintf(STDERR_FILENO, "exec %s failed: %s\n", d->cfg->sps_bin, strerror(errno));
    _exit(127);
  }
  close(po[1]);
  close(pe[1]);
  if (pid < 0) {
    close(po[0]), close(pe[0]);
    return -1;
  }
  *out_fd = po[0];
  *err_fd = pe[0];
  return pid;
}

/* Runs shairport-sync, moves its PCM into the stream and its log into ours. */
static void *audio_thread(void *arg) {
  device *d = arg;
  char conf[512];
  int backoff = 1000;
  size_t fb = stream_frame_bytes(&d->st);
  uint8_t *buf = malloc(16384 + fb);
  char line[1024];
  size_t ll = 0;
  if (!buf)
    return NULL;
  while (!d->stop) {
    if (write_sps_config(d, conf, sizeof(conf)) < 0)
      break;
    int out_fd, err_fd;
    pid_t pid = spawn_sps(d, conf, &out_fd, &err_fd);
    if (pid < 0) {
      LOGE("%s: cannot start shairport-sync: %s", d->tag, strerror(errno));
      break;
    }
    pthread_mutex_lock(&d->mu);
    d->sps_pid = pid;
    pthread_mutex_unlock(&d->mu);
    LOGI("%s: AirPlay 2 receiver \"%s\" started (pid %d, port %d)", d->tag, d->airplay_name,
         (int)pid, d->cfg->base_port + d->slot);
    int64_t started = now_ms();
    size_t carry = 0;
    int open_fds = 2;
    while (open_fds > 0) {
      struct pollfd p[2] = {{.fd = out_fd, .events = POLLIN}, {.fd = err_fd, .events = POLLIN}};
      if (poll(p, 2, 500) < 0 && errno != EINTR)
        break;
      if (out_fd >= 0 && (p[0].revents & (POLLIN | POLLHUP | POLLERR))) {
        ssize_t n = read(out_fd, buf + carry, 16384);
        if (n <= 0) {
          close(out_fd);
          out_fd = -1;
          open_fds--;
        } else {
          size_t total = carry + (size_t)n, whole = total - total % fb;
          if (whole)
            stream_write(&d->st, buf, whole);
          carry = total - whole;
          if (carry)
            memmove(buf, buf + whole, carry);
        }
      }
      if (err_fd >= 0 && (p[1].revents & (POLLIN | POLLHUP | POLLERR))) {
        ssize_t n = read(err_fd, line + ll, sizeof(line) - 1 - ll);
        if (n <= 0) {
          close(err_fd);
          err_fd = -1;
          open_fds--;
        } else {
          ll += (size_t)n;
          line[ll] = 0;
          char *nl;
          while ((nl = strchr(line, '\n'))) {
            *nl = 0;
            if (*line)
              LOGI("%s: sps: %s", d->tag, line);
            ll -= (size_t)(nl + 1 - line);
            memmove(line, nl + 1, ll + 1);
          }
          if (ll >= sizeof(line) - 1) { /* overlong line */
            LOGI("%s: sps: %s", d->tag, line);
            ll = 0;
          }
        }
      }
    }
    if (out_fd >= 0)
      close(out_fd);
    if (err_fd >= 0)
      close(err_fd);
    int status = 0;
    waitpid(pid, &status, 0);
    pthread_mutex_lock(&d->mu);
    d->sps_pid = 0;
    pthread_mutex_unlock(&d->mu);
    if (d->stop)
      break;
    if (WIFEXITED(status))
      LOGW("%s: shairport-sync exited with status %d", d->tag, WEXITSTATUS(status));
    else if (WIFSIGNALED(status))
      LOGW("%s: shairport-sync killed by signal %d", d->tag, WTERMSIG(status));
    if (now_ms() - started > 60000)
      backoff = 1000;
    for (int waited = 0; waited < backoff && !d->stop; waited += 100)
      usleep(100000);
    backoff = backoff * 2 > 30000 ? 30000 : backoff * 2;
  }
  free(buf);
  return NULL;
}

/* ---------------------------------------------------------------- metadata */

static void handle_meta(device *d, const uint8_t *pkt, size_t len) {
  if (len < 8)
    return;
  char type[5], code[5];
  memcpy(type, pkt, 4), type[4] = 0;
  memcpy(code, pkt + 4, 4), code[4] = 0;
  char data[512];
  size_t dl = len - 8 < sizeof(data) - 1 ? len - 8 : sizeof(data) - 1;
  memcpy(data, pkt + 8, dl);
  data[dl] = 0;

  if (!strcmp(type, "ssnc")) {
    if (!strcmp(code, "pbeg")) {
      LOGI("%s: AirPlay play begin", d->tag);
      d->ap_active = 1;
      d->preempted = 0;
    } else if (!strcmp(code, "pend")) {
      LOGI("%s: AirPlay play end", d->tag);
      d->ap_active = 0;
    } else if (!strcmp(code, "pfls")) {
      LOGI("%s: AirPlay flush", d->tag);
      if (d->cfg->flush_stop)
        d->flushed = 1;
    } else if (!strcmp(code, "prsm")) {
      LOGI("%s: AirPlay resume", d->tag);
      d->preempted = 0;
    } else if (!strcmp(code, "paus")) {
      LOGI("%s: AirPlay pause", d->tag);
    } else if (!strcmp(code, "pvol")) {
      double av;
      if (sscanf(data, "%lf", &av) == 1) {
        d->ap_volume_db = av;
        d->volume_dirty = 1;
        LOGD("%s: AirPlay volume %.2f dB", d->tag, av);
      }
    } else if (!strcmp(code, "abeg") || !strcmp(code, "aend")) {
      LOGI("%s: AirPlay %s active state", d->tag, code[0] == 'a' && code[1] == 'b' ? "enter" : "exit");
    } else if (!strcmp(code, "conn") || !strcmp(code, "disc")) {
      LOGI("%s: AirPlay client %s %s", d->tag, code[0] == 'c' ? "connected from" : "disconnected", data);
    } else if (!strcmp(code, "styp")) {
      LOGI("%s: AirPlay stream type %s", d->tag, data);
    }
  } else if (!strcmp(type, "core")) {
    if (!strcmp(code, "minm"))
      snprintf(d->title, sizeof(d->title), "%s", data);
    else if (!strcmp(code, "asar"))
      snprintf(d->artist, sizeof(d->artist), "%s", data);
  }
}

/* ---------------------------------------------------------------- cast control */

static void restore_duck(device *d, int force) {
  if (d->duck_saved < 0)
    return;
  double duck = d->cfg->duck_percent / 100.0;
  if (cast_is_open(&d->cc)) {
    if (!force && d->cc.have_volume && fabs(d->cc.volume - duck) > 0.015) {
      LOGI("%s: speaker volume changed to %.2f during launch; leaving it", d->tag, d->cc.volume);
    } else {
      LOGI("%s: restoring speaker volume %.2f", d->tag, d->duck_saved);
      cast_set_volume(&d->cc, d->duck_saved, 3000);
    }
  }
  d->duck_saved = -1;
}

static int start_cast(device *d) {
  cast_device info;
  pthread_mutex_lock(&d->mu);
  info = d->info;
  pthread_mutex_unlock(&d->mu);
  if (!cast_is_open(&d->cc) && cast_open(&d->cc, d->tag, info.ip, info.port, 5000) < 0)
    return -1;
  if (strcmp(d->cc.app_id, CAST_APP_DEFAULT_MEDIA_RECEIVER) || !d->cc.transport_id[0]) {
    double duck = d->cfg->duck_percent / 100.0;
    if (d->cfg->duck_percent > 0 && d->cc.have_volume && !d->cc.muted && d->cc.volume > duck &&
        d->duck_saved < 0) {
      double saved = d->cc.volume;
      LOGI("%s: lowering speaker volume %.2f -> %.2f for the launch chime", d->tag, saved, duck);
      if (cast_set_volume(&d->cc, duck, 3000) == 0)
        d->duck_saved = saved;
    }
    if (cast_launch(&d->cc, CAST_APP_DEFAULT_MEDIA_RECEIVER, 15000) < 0) {
      restore_duck(d, 1);
      return -1;
    }
    d->ours = 1;
    d->launch_ms = now_ms();
    d->duck_until_ms = d->launch_ms + DUCK_HOLD_MS;
  }
  char ip[64];
  if (d->cfg->http_ip[0])
    snprintf(ip, sizeof(ip), "%s", d->cfg->http_ip);
  else if (local_ip_for(info.ip, ip, sizeof(ip)) < 0) {
    LOGW("%s: no local address routes to %s", d->tag, info.ip);
    return -1;
  }
  char url[256];
  snprintf(url, sizeof(url), "http://%s:%d%s", ip, d->cfg->http_port, d->st.path);
  stream_kick_clients(&d->st); /* drop connections from a previous load */
  if (cast_load(&d->cc, url, CONTENT_TYPE, d->title[0] ? d->title : d->airplay_name,
                d->artist[0] ? d->artist : "AirPlay", 10000) < 0) {
    restore_duck(d, 1);
    return -1;
  }
  d->media_loaded = 1;
  if (d->cfg->hw_volume)
    d->volume_dirty = 1;
  return 0;
}

static void release_cast(device *d, const char *why) {
  if (!cast_is_open(&d->cc))
    return;
  restore_duck(d, 1);
  if (d->ours && !strcmp(d->cc.app_id, CAST_APP_DEFAULT_MEDIA_RECEIVER)) {
    LOGI("%s: releasing speaker (%s)", d->tag, why);
    cast_stop_app(&d->cc, 3000);
  }
  cast_close(&d->cc);
  d->media_loaded = 0;
  d->ours = 0;
}

static void tick(device *d) {
  int64_t t = now_ms();
  int64_t last = stream_last_write(&d->st);
  int has_audio = last && t - last < 500;

  if (d->flushed) {
    d->flushed = 0;
    stream_mark_session_next(&d->st);
    if (d->media_loaded && cast_is_open(&d->cc)) {
      /* cut stale audio buffered in the speaker; audio after the flush reloads */
      cast_media_command(&d->cc, "STOP", 3000);
      d->media_loaded = 0;
    }
    stream_kick_clients(&d->st);
  }

  if (!has_audio && last && t - last > 5000)
    d->preempted = 0; /* a later session may take the speaker again */

  /* track what the receiver is doing */
  if (d->media_loaded) {
    if (!cast_is_open(&d->cc) || strcmp(d->cc.app_id, CAST_APP_DEFAULT_MEDIA_RECEIVER) ||
        !d->cc.transport_id[0]) {
      d->media_loaded = 0;
      if (cast_is_open(&d->cc) && d->cc.app_id[0]) {
        LOGI("%s: speaker taken over by app %s; not reclaiming during this session", d->tag,
             d->cc.app_id);
        d->preempted = 1;
        d->ours = 0;
      }
    } else if (!strcmp(d->cc.player_state, "IDLE") && d->cc.idle_reason[0]) {
      /* IDLE without a reason is the normal state right after LOAD */
      const char *r = d->cc.idle_reason;
      d->media_loaded = 0;
      if (!strcmp(r, "INTERRUPTED") || !strcmp(r, "CANCELLED")) {
        LOGI("%s: media replaced by another sender", d->tag);
        d->preempted = 1;
      } else {
        d->next_retry_ms = t + 1000; /* ERROR/FINISHED: reload shortly */
      }
    }
  }

  if (has_audio && !d->media_loaded && !d->preempted && t >= d->next_retry_ms) {
    if (start_cast(d) < 0) {
      d->next_retry_ms = now_ms() + RETRY_MS;
      LOGW("%s: cast start failed, retrying in %d s", d->tag, RETRY_MS / 1000);
    }
    t = now_ms();
  }

  if (cast_is_open(&d->cc)) {
    if (d->duck_saved >= 0 && t >= d->duck_until_ms &&
        (!strcmp(d->cc.player_state, "PLAYING") || t - d->launch_ms > DUCK_MAX_MS))
      restore_duck(d, 0);
    if (d->volume_dirty && d->cfg->hw_volume && d->duck_saved < 0) {
      d->volume_dirty = 0;
      cast_set_volume(&d->cc, airplay_db_to_level(d->ap_volume_db), 3000);
    }
    int64_t quiet = last ? t - last : t - d->launch_ms;
    if (!has_audio && quiet > (int64_t)d->cfg->idle_timeout_s * 1000 && !d->ap_active)
      release_cast(d, "idle");
    else if (!has_audio && !d->media_loaded && !d->ours && quiet > 10000)
      cast_close(&d->cc); /* nothing of ours on the speaker */
  }
}

static void *ctl_thread(void *arg) {
  device *d = arg;
  uint8_t pkt[65536];
  while (!d->stop) {
    struct pollfd p[2] = {{.fd = d->meta_fd, .events = POLLIN}, {.fd = cast_fd(&d->cc), .events = POLLIN}};
    int np = cast_is_open(&d->cc) ? 2 : 1;
    poll(p, (nfds_t)np, 100);
    if (p[0].revents & POLLIN) {
      ssize_t n;
      while ((n = recv(d->meta_fd, pkt, sizeof(pkt), MSG_DONTWAIT)) > 0)
        handle_meta(d, pkt, (size_t)n);
    }
    if (cast_is_open(&d->cc))
      cast_pump(&d->cc, 0);
    tick(d);
  }
  release_cast(d, "shutdown");
  return NULL;
}

/* ---------------------------------------------------------------- lifecycle */

device *device_start(const cast_device *info, int slot, const bridge_config *cfg) {
  device *d = calloc(1, sizeof(*d));
  if (!d)
    return NULL;
  d->info = *info;
  d->slot = slot;
  d->cfg = cfg;
  d->cc.fd = -1;
  d->duck_saved = -1;
  d->ap_volume_db = -15;
  snprintf(d->tag, sizeof(d->tag), "[%s]", info->name);
  snprintf(d->airplay_name, sizeof(d->airplay_name), "%s%s", info->name, cfg->suffix);
  pthread_mutex_init(&d->mu, NULL);
  if (stream_init(&d->st, info->id, cfg->rate, 2, cfg->ring_ms, cfg->backlog_ms) < 0)
    goto fail;
  d->meta_fd = socket(AF_INET, SOCK_DGRAM | SOCK_CLOEXEC, 0);
  struct sockaddr_in a = {.sin_family = AF_INET, .sin_addr.s_addr = htonl(INADDR_LOOPBACK)};
  socklen_t al = sizeof(a);
  if (d->meta_fd < 0 || bind(d->meta_fd, (struct sockaddr *)&a, sizeof(a)) < 0 ||
      getsockname(d->meta_fd, (struct sockaddr *)&a, &al) < 0)
    goto fail;
  int rcv = 1 << 20;
  setsockopt(d->meta_fd, SOL_SOCKET, SO_RCVBUF, &rcv, sizeof(rcv));
  d->meta_port = ntohs(a.sin_port);
  http_register(&d->st);
  if (pthread_create(&d->ctl_thr, NULL, ctl_thread, d) != 0)
    goto fail;
  if (pthread_create(&d->audio_thr, NULL, audio_thread, d) != 0) {
    d->stop = 1;
    pthread_join(d->ctl_thr, NULL);
    goto fail;
  }
  LOGI("%s: added %s (%s) at %s:%d", d->tag, info->model, info->id, info->ip, info->port);
  return d;
fail:
  LOGE("%s: cannot start device", d->tag);
  if (d->meta_fd > 0)
    close(d->meta_fd);
  if (d->st.buf)
    stream_destroy(&d->st);
  free(d);
  return NULL;
}

void device_stop(device *d) {
  d->stop = 1;
  pthread_mutex_lock(&d->mu);
  if (d->sps_pid > 0)
    kill(d->sps_pid, SIGTERM);
  pthread_mutex_unlock(&d->mu);
  pthread_join(d->ctl_thr, NULL);
  pthread_join(d->audio_thr, NULL);
  stream_destroy(&d->st);
  close(d->meta_fd);
  char conf[512];
  snprintf(conf, sizeof(conf), "%s/%s.conf", d->cfg->state_dir, d->info.id);
  unlink(conf);
  LOGI("%s: removed", d->tag);
  pthread_mutex_destroy(&d->mu);
  free(d);
}

int device_is_busy(device *d) {
  int64_t last = stream_last_write(&d->st);
  return d->ap_active || d->media_loaded || (last && now_ms() - last < 10000);
}

/* ---------------------------------------------------------------- test tone */

typedef struct {
  stream *st;
  double freq;
  volatile int stop;
} tone_arg;

static void *tone_thread(void *arg) {
  tone_arg *ta = arg;
  int rate = ta->st->rate;
  int frames = rate / 50; /* 20 ms */
  int16_t *buf = malloc((size_t)frames * 4);
  double phase = 0, step = 2 * M_PI * ta->freq / rate;
  int64_t t0 = now_ms(), produced = 0;
  while (!ta->stop) {
    for (int i = 0; i < frames; i++) {
      /* quiet (-26 dBFS) tone, 0.6 s on / 0.4 s off so it is recognisable */
      int64_t f = produced * frames + i;
      double env = (f % rate) < rate * 6 / 10 ? 0.05 : 0.0;
      int16_t v = (int16_t)(sin(phase) * env * 32767);
      phase += step;
      if (phase > 2 * M_PI)
        phase -= 2 * M_PI;
      buf[2 * i] = buf[2 * i + 1] = v;
    }
    stream_write(ta->st, (uint8_t *)buf, (size_t)frames * 4);
    produced++;
    int64_t due = t0 + produced * 20;
    int64_t wait = due - now_ms();
    if (wait > 0)
      usleep((useconds_t)wait * 1000);
  }
  free(buf);
  return NULL;
}

int bridge_cast_test(const bridge_config *cfg, const cast_device *dev, int seconds, double freq) {
  device d;
  memset(&d, 0, sizeof(d));
  d.info = *dev;
  d.cfg = cfg;
  d.cc.fd = -1;
  d.duck_saved = -1;
  snprintf(d.tag, sizeof(d.tag), "[%s]", dev->name);
  snprintf(d.airplay_name, sizeof(d.airplay_name), "airplay2cast test tone");
  pthread_mutex_init(&d.mu, NULL);
  if (stream_init(&d.st, dev->id, cfg->rate, 2, cfg->ring_ms, cfg->backlog_ms) < 0)
    return -1;
  http_register(&d.st);
  tone_arg ta = {.st = &d.st, .freq = freq};
  pthread_t tt;
  pthread_create(&tt, NULL, tone_thread, &ta);
  usleep(300000);
  int rc = start_cast(&d);
  if (rc == 0) {
    int64_t end = now_ms() + seconds * 1000LL, next_log = 0;
    while (now_ms() < end && cast_is_open(&d.cc)) {
      cast_pump(&d.cc, 100);
      tick(&d);
      if (now_ms() >= next_log) {
        cast_media_command(&d.cc, "GET_STATUS", 1000);
        double delivered = (double)d.st.client_sent / (cfg->rate * 4.0);
        LOGI("%s: player=%s position=%.1f s delivered=%.1f s latency=%.1f s clients=%d", d.tag,
             d.cc.player_state, d.cc.current_time, delivered, delivered - d.cc.current_time,
             stream_client_count(&d.st));
        next_log = now_ms() + 2000;
      }
    }
    rc = strcmp(d.cc.player_state, "PLAYING") ? -1 : 0;
  }
  release_cast(&d, "test finished");
  ta.stop = 1;
  pthread_join(tt, NULL);
  stream_destroy(&d.st);
  return rc;
}
